/// verbatim since v4.12: owner defect «بخش اسم پرچم کشورها باید اسم کشورها
/// باشه نه کد کشورها») plus the app's four other first-class tables.
///
/// v6 (owner round 23: «در زبان های مختلف لوکیشن اتصال همچنان به زبان فارسی
/// نوشته میشه که این مشکل باید حل بشه و نام لوکیشن های اتصال هم باید برای
/// همه زبان های اپ ترجمه بشه و در دسترس قرار بگیره») — the connection
/// location's name now resolves through the ACTIVE LOCALE's own table:
/// fa / en / ru / zh / tk, generated from the ISO 3166 databases and the
/// iso-codes gettext locales (pycountry 24.6.1: ru, tk, zh_CN) with the
/// artwork pack's extended codes (gb-eng, es-ct, eu, un, xk, cefta, ac,
/// ta, ic, cp, dg, ea) hand-checked — see scripts/gen_country_tables.py.
/// The egress / exit sets (the locations a session can actually land on)
/// are covered in every table; tk's remaining iso-codes gaps fall back to
/// ENGLISH (the app's declared fallback tongue), never to a raw code.
///
/// The flags bundle ships 266 artworks (`design/flags_png/<code>.png`,
/// alpha-2 ISO codes plus the extended set). A widget/asset test keeps
/// every table complete against the asset manifest.
library;

/// Display name for a flag code in [locale]'s language (null = Persian,
/// the design language); unknown locales resolve the English table. The
/// per-entry fallback chain is: the locale's own table → English → the
/// upper-cased code (guarded to never happen by the completeness test).
///
/// v4.21: the wheel's AUTO sentinel ('auto' — the core's own location
/// choice, owner: «این انتخاب خودکار قابلیت خود هسته هاست») renders per
/// locale («خودکار» / Automatic / Автоматически / 自动 / Awtomatiki)
/// instead of a country name.
String? countryName(String? code, {String? locale}) {
  if (code == null) return null;
  if (code == 'auto') {
    return _autoLabels[locale] ?? _autoLabels['fa']!;
  }
  // Null locale = Persian (the design language, AppStrings' own rule);
  // an unmapped locale resolves the English table.
  final table = _tables[locale ?? 'fa'] ?? _namesEn;
  return table[code] ?? _namesEn[code] ?? code.toUpperCase();
}

