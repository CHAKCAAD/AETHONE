///
/// The location header and the routing page show the selected country's
/// name in the APP'S OWN LANGUAGE (owner decree: the name used to read
/// Persian in every locale). en/ru/zh/tk are generated from the CLDR
/// territory display names (unicode-org/cldr-json, CLDR 46 — © Unicode,
/// terms of use: https://www.unicode.org/copyright.html), restricted to
/// the app's own flag-manifest codes; the Persian table is the owner's
/// hand-written map, carried over VERBATIM (the decree adds languages,
/// it does not re-word the Persian display).
///
/// Resolution: the ambient app language (fa/en/ru/zh/tk) → any code the
/// table misses falls back to Persian (the design language) → then to
/// the upper-cased code itself (the honest, never-wrong last resort).
/// 'auto' keeps its own localized label in every locale.
library;

/// The display name for [code] ('ir', 'de', …, or the 'auto' sentinel)
/// under [languageCode] (the app locale; null = fa, the design language).
String? countryName(String? code, {String? languageCode}) {
  if (code == null) return null;
  final c = code.toLowerCase();
  if (c == 'auto') {
    final auto = _autoLabels[languageCode ?? 'fa'];
    return auto ?? _autoLabels['fa']!;
  }
  final table = _tables[languageCode] ?? _tables['fa']!;
  return table[c] ?? _tables['fa']![c] ?? code.toUpperCase();
}

